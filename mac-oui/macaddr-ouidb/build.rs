use std::fs;
use std::path::Path;

use macaddr_ouidb_support::layout::OuiLoc;
use macaddr_ouidb_support::regdate::SENTINEL;
use macaddr_ouidb_support::{OuiDataBuilder, SubtableRef};

/// Generates Rust code: produces `oui_data.rs` from the intermediate `builder` data structure
fn generate_code(builder: &OuiDataBuilder, output_path: &Path, regdate: bool) {
    let mut code = String::new();

    // Build the names string
    let names_string: String = builder.names.join("");

    // Compute the offset of each name
    let mut name_offsets: Vec<usize> = Vec::with_capacity(builder.names.len());
    let mut current_offset = 0;
    for name in &builder.names {
        name_offsets.push(current_offset);
        current_offset += name.len();
    }

    // Build the oui_24 prefix list (used for statistics)
    let oui24_prefixes: Vec<[u8; 3]> = builder.oui24_map.keys().copied().collect();

    // Total length of all unique names
    let unique_names_total_length: usize = names_string.len();

    // 高字节 0xFF 被用作子表标记，因此 names 的 offset 必须始终小于 0x7F_8000，
    // 否则某个 names loc 的高字节会撞上 0xFF，被误判为子表指针。此处提前失败。
    assert!(
        unique_names_total_length < 0x7F_8000,
        "names pool too large ({unique_names_total_length} bytes); \
         offset high byte would collide with the 0xFF subtable tag"
    );

    // Collect name-length statistics
    let name_lengths: Vec<usize> = builder.names.iter().map(|s| s.len()).collect();
    let min_name_len = name_lengths.iter().min().copied().unwrap_or(0);
    let max_name_len = name_lengths.iter().max().copied().unwrap_or(0);

    // names length 由 `OuiLoc` 的 9 位字段限制；这里做一次性硬校验，
    // 避免在每个 loc 生成点重复断言。（`offset` 由上面的 pool 大小守卫覆盖。）
    assert!(
        max_name_len <= OuiLoc::MAX_LENGTH,
        "name too long ({max_name_len} bytes); exceeds the 9-bit OuiLoc length field"
    );

    // File header - add generation info and statistics
    code.push_str("// Auto-generated by macaddr-oui-codegen\n");
    code.push_str("// DO NOT EDIT MANUALLY\n");
    code.push_str("// rustfmt-off\n\n");

    // Add the statistics comment
    code.push_str("// === Generation Statistics ===\n");
    code.push_str(&format!(
        "// - Unique names: {}, total length: {unique_names_total_length}\n",
        builder.names.len()
    ));
    code.push_str(&format!(
        "// - Name length: min={}, max={}\n",
        min_name_len, max_name_len
    ));
    code.push_str(&format!("// - OUI-24 entries: {}\n", oui24_prefixes.len()));
    let oui28_entries: usize = builder.oui28_tables.iter().map(|t| t.len()).sum();
    code.push_str(&format!(
        "// - OUI-28 tables: {}, entries: {}\n",
        builder.oui28_tables.len(),
        oui28_entries
    ));
    {
        let oui36_entries: usize = builder.oui36_tables.iter().map(|t| t.len()).sum();
        code.push_str(&format!(
            "// - OUI-36 tables: {}, entries: {}\n",
            builder.oui36_tables.len(),
            oui36_entries
        ));
    }
    code.push_str(&format!(
        "// - Subtable-only prefixes: {}\n",
        builder.subtable_only_prefixes.len()
    ));
    code.push_str(&format!("// - Generated file size: {} bytes\n", 0)); // updated later
    code.push_str("// ============================\n\n");

    // Add the subtable-only prefix log (prefixes that have subtables but no 24-bit entry)
    if !builder.subtable_only_prefixes.is_empty() {
        code.push_str("// === Subtable-Only Prefixes (No 24-bit OUI Entry) ===\n");
        code.push_str(
            "// These prefixes have only subtables (28/36-bit) without a 24-bit OUI entry\n",
        );
        code.push_str("// Format: // - XX:XX:XX (TYPE, N entries)\n");
        for (prefix, subtable_type, entry_count) in &builder.subtable_only_prefixes {
            let type_str = match subtable_type {
                SubtableRef::Oui28(_) => "OUI-28",
                SubtableRef::Oui36(_) => "OUI-36",
            };
            code.push_str(&format!(
                "// - {:02X}{:02X}{:02X} ({}, {} entries)\n",
                prefix[0], prefix[1], prefix[2], type_str, entry_count
            ));
        }
        code.push_str("// ================================================\n\n");
    }

    code.push_str("use crate::oui::OuiLoc;\n\n");
    code.push_str("use crate::oui::SubtableDesc;\n\n");
    code.push_str("use crate::oui::OuiDbBundled;\n\n");

    // Generate the names constant
    code.push_str(&format!(
        "const OUI_NAMES: &str = r#\"{}\"#;\n\n",
        names_string
    ));

    // Generate the oui_24 prefix/loc columns - data embedded directly
    code.push_str("#[rustfmt::skip]\n");
    code.push_str("const OUI_24_PREFIX: &[[u8; 3]] = &[\n        ");

    // prefix column - 20 items per line
    for (i, prefix) in oui24_prefixes.iter().enumerate() {
        if i > 0 && i % 20 == 0 {
            code.push_str("\n        ");
        }
        code.push_str(&format!("[{},{},{}],", prefix[0], prefix[1], prefix[2]));
    }
    code.push_str("\n];\n\n");

    // loc column - 30 items per line
    code.push_str("#[rustfmt::skip]\n");
    code.push_str("const OUI_24_LOC: &[OuiLoc] = &[\n        ");
    for (i, prefix) in oui24_prefixes.iter().enumerate() {
        if i > 0 && i % 30 == 0 {
            code.push_str("\n        ");
        }
        let (name_idx, subtable) = builder.oui24_map.get(prefix).unwrap();
        let loc = match subtable {
            Some(SubtableRef::Oui28(idx)) => OuiLoc::subtable(false, *idx),
            Some(SubtableRef::Oui36(idx)) => OuiLoc::subtable(true, *idx),
            None => {
                // high byte != 0xFF: points into names, offset 23 bits, length 9 bits
                let offset = name_offsets[*name_idx];
                let length = builder.names[*name_idx].len();
                OuiLoc::names(offset, length)
            }
        };
        code.push_str(&format!("OuiLoc::new(0x{:08X}),", loc.value()));
    }
    code.push_str("\n];\n\n");

    // Generate the oui_24 registration-date column (parallel to OUI_24_PREFIX)
    if regdate {
        code.push_str("#[rustfmt::skip]\n");
        code.push_str("const OUI_24_REGDATE: &[u16] = &[\n        ");
        for (i, prefix) in oui24_prefixes.iter().enumerate() {
            if i > 0 && i % 20 == 0 {
                code.push_str("\n        ");
            }
            let d = builder.regdate24.get(prefix).copied().unwrap_or(SENTINEL);
            code.push_str(&format!("{d},"));
        }
        code.push_str("\n];\n\n");
    }

    // Generate the oui_28 subtable descriptors + prefix/loc memory pools.
    // Layout matches `OuiDbOwned`: all subtable prefixes and locs are concatenated
    // into contiguous pools, and each subtable is described by a `SubtableDesc`
    // (offset + length) rather than holding its own slice.
    code.push_str("#[rustfmt::skip]\n");
    code.push_str("const OUI_28_TABLES: &[SubtableDesc] = &[\n");
    {
        let mut prefix_pool: Vec<u8> = Vec::new();
        let mut loc_pool: Vec<OuiLoc> = Vec::new();
        let mut regdate_pool: Vec<u16> = Vec::new();
        for (idx, table) in builder.oui28_tables.iter().enumerate() {
            let prefix3 = builder.oui28_idx_to_prefix.get(&idx).unwrap();
            let prefix_start = prefix_pool.len() as u32;
            let loc_start = loc_pool.len() as u32;
            prefix_pool.extend(table.iter().map(|e| e.prefix));
            for entry in table {
                let offset = name_offsets[entry.name_idx];
                let length = builder.names[entry.name_idx].len();
                loc_pool.push(OuiLoc::names(offset, length));
                regdate_pool.push(entry.regdate);
            }
            assert!(
                table.len() <= OuiLoc::MAX_SUBTABLE_INDEX + 1,
                "oui_28 subtable too large: {}",
                table.len()
            );
            let len = table.len() as u16;
            code.push_str(&format!(
                "    /* {:02X}{:02X}{:02X} */ SubtableDesc {{ prefix_start: {}, loc_start: {}, prefix_len: {}, loc_len: {} }},\n",
                prefix3[0], prefix3[1], prefix3[2], prefix_start, loc_start, len, len
            ));
        }
        code.push_str("];\n\n");

        // prefix pool (u8)
        code.push_str("#[rustfmt::skip]\n");
        code.push_str("const OUI_28_PREFIX_POOL: &[u8] = &[");
        for (i, p) in prefix_pool.iter().enumerate() {
            if i > 0 {
                code.push(',');
            }
            code.push_str(&format!("0x{p:02X}"));
        }
        code.push_str("];\n\n");

        // loc pool (u32)
        code.push_str("#[rustfmt::skip]\n");
        code.push_str("const OUI_28_LOC_POOL: &[OuiLoc] = &[\n        ");
        for (i, l) in loc_pool.iter().enumerate() {
            if i > 0 {
                code.push(',');
            }
            if i > 0 && i % 8 == 0 {
                code.push_str("\n        ");
            }
            code.push_str(&format!("OuiLoc::new(0x{:08X})", l.value()));
        }
        code.push_str("\n];\n\n");

        if regdate {
            code.push_str("#[rustfmt::skip]\n");
            code.push_str("const OUI_28_REGDATE_POOL: &[u16] = &[\n        ");
            for (i, d) in regdate_pool.iter().enumerate() {
                if i > 0 && i % 20 == 0 {
                    code.push_str("\n        ");
                }
                code.push_str(&format!("{d},"));
            }
            code.push_str("\n];\n\n");
        }
    }

    // Generate the oui_36 subtable descriptors + prefix/loc memory pools (same layout).
    code.push_str("#[rustfmt::skip]\n");
    code.push_str("const OUI_36_TABLES: &[SubtableDesc] = &[\n");
    {
        let mut prefix_pool: Vec<u16> = Vec::new();
        let mut loc_pool: Vec<OuiLoc> = Vec::new();
        let mut regdate_pool: Vec<u16> = Vec::new();
        for (idx, table) in builder.oui36_tables.iter().enumerate() {
            let prefix3 = builder.oui36_idx_to_prefix.get(&idx).unwrap();
            let prefix_start = prefix_pool.len() as u32;
            let loc_start = loc_pool.len() as u32;
            prefix_pool.extend(table.iter().map(|e| e.prefix));
            for entry in table {
                let offset = name_offsets[entry.name_idx];
                let length = builder.names[entry.name_idx].len();
                loc_pool.push(OuiLoc::names(offset, length));
                regdate_pool.push(entry.regdate);
            }
            assert!(
                table.len() <= OuiLoc::MAX_SUBTABLE_INDEX + 1,
                "oui_36 subtable too large: {}",
                table.len()
            );
            let len = table.len() as u16;
            code.push_str(&format!(
                "    /* {:02X}{:02X}{:02X} */ SubtableDesc {{ prefix_start: {}, loc_start: {}, prefix_len: {}, loc_len: {} }},\n",
                prefix3[0], prefix3[1], prefix3[2], prefix_start, loc_start, len, len
            ));
        }
        code.push_str("];\n\n");

        // prefix pool (u16)
        code.push_str("#[rustfmt::skip]\n");
        code.push_str("const OUI_36_PREFIX_POOL: &[u16] = &[");
        for (i, p) in prefix_pool.iter().enumerate() {
            if i > 0 {
                code.push(',');
            }
            code.push_str(&format!("0x{p:04X}"));
        }
        code.push_str("];\n\n");

        // loc pool (u32)
        code.push_str("#[rustfmt::skip]\n");
        code.push_str("const OUI_36_LOC_POOL: &[OuiLoc] = &[\n        ");
        for (i, l) in loc_pool.iter().enumerate() {
            if i > 0 {
                code.push(',');
            }
            if i > 0 && i % 8 == 0 {
                code.push_str("\n        ");
            }
            code.push_str(&format!("OuiLoc::new(0x{:08X})", l.value()));
        }
        code.push_str("\n];\n\n");

        if regdate {
            code.push_str("#[rustfmt::skip]\n");
            code.push_str("const OUI_36_REGDATE_POOL: &[u16] = &[\n        ");
            for (i, d) in regdate_pool.iter().enumerate() {
                if i > 0 && i % 20 == 0 {
                    code.push_str("\n        ");
                }
                code.push_str(&format!("{d},"));
            }
            code.push_str("\n];\n\n");
        }
    }

    // Generate the OuiDbBundled constant
    code.push_str("/// Bundled (compile-time) OUI database\n");
    code.push_str("pub const OUI_DB_BUNDLED: OuiDbBundled = OuiDbBundled {\n");
    code.push_str(&format!("    updated: \"{}\",\n", builder.updated));
    code.push_str("    names: OUI_NAMES,\n");
    code.push_str("    oui_24_prefix: OUI_24_PREFIX,\n");
    code.push_str("    oui_24_loc: OUI_24_LOC,\n");
    if regdate {
        code.push_str("    #[cfg(feature = \"regdate\")]\n");
        code.push_str("    oui_24_regdate: OUI_24_REGDATE,\n");
    }
    code.push_str("    oui_28: OUI_28_TABLES,\n");
    code.push_str("    prefix_pool_28: OUI_28_PREFIX_POOL,\n");
    code.push_str("    loc_pool_28: OUI_28_LOC_POOL,\n");
    if regdate {
        code.push_str("    #[cfg(feature = \"regdate\")]\n");
        code.push_str("    regdate_pool_28: OUI_28_REGDATE_POOL,\n");
    }
    code.push_str("    oui_36: OUI_36_TABLES,\n");
    code.push_str("    prefix_pool_36: OUI_36_PREFIX_POOL,\n");
    code.push_str("    loc_pool_36: OUI_36_LOC_POOL,\n");
    if regdate {
        code.push_str("    #[cfg(feature = \"regdate\")]\n");
        code.push_str("    regdate_pool_36: OUI_36_REGDATE_POOL,\n");
    }
    code.push_str("};\n");

    // Update the generated-file-size statistic (replace the placeholder)
    let code = code.replace(
        "// - Generated file size: 0 bytes",
        &format!("// - Generated file size: {} bytes", code.len()),
    );

    // Check whether the file already exists with identical content to avoid unnecessary writes
    let needs_write = if output_path.exists() {
        if let Ok(existing) = fs::read_to_string(output_path) {
            existing != code
        } else {
            println!("cargo:warning=Failed to read generated file",);
            true
        }
    } else {
        println!("cargo:warning=Generated file does NOT exist",);
        true
    };

    if needs_write {
        fs::write(output_path, &code).expect("Failed to write output file");
        // Print build info to stdout (for cargo to display)
        println!(
            "cargo:warning=Generated {} with {} bytes",
            output_path.display(),
            code.len()
        );
    } else {
        println!(
            "cargo:warning={} is up to date, skipped",
            output_path.display()
        );
        return;
    }
    println!("cargo:warning=Statistics:");
    println!(
        "cargo:warning=  - Unique names: {}, total length: {unique_names_total_length}",
        builder.names.len()
    );
    println!(
        "cargo:warning=  - Name length: min={}, max={}",
        min_name_len, max_name_len
    );
    println!("cargo:warning=  - OUI-24 entries: {}", oui24_prefixes.len());
    println!(
        "cargo:warning=  - OUI-28 tables: {}, entries: {}",
        builder.oui28_tables.len(),
        oui28_entries
    );
    {
        let oui36_entries: usize = builder.oui36_tables.iter().map(|t| t.len()).sum();
        println!(
            "cargo:warning=  - OUI-36 tables: {}, entries: {}",
            builder.oui36_tables.len(),
            oui36_entries
        );
    }
    println!("cargo:warning=Subtable-only prefixes (no 24-bit OUI entry):");
    for (prefix, subtable_type, entry_count) in &builder.subtable_only_prefixes {
        let type_str = match subtable_type {
            SubtableRef::Oui28(_) => "OUI-28",
            SubtableRef::Oui36(_) => "OUI-36",
        };
        println!(
            "cargo:warning=  - {:02X}{:02X}{:02X} ({}, {} entries)",
            prefix[0], prefix[1], prefix[2], type_str, entry_count
        );
    }
}

fn main() {
    // Watch source files for changes
    println!("cargo:rerun-if-changed=build.rs");

    // The `address` feature takes precedence over `fullname` for the data source
    let use_address = std::env::var("CARGO_FEATURE_ADDRESS").is_ok();
    let use_fullname = std::env::var("CARGO_FEATURE_FULLNAME").is_ok();
    let ieee_file = if use_address {
        "ieee-mac-oui-address.txt"
    } else if use_fullname {
        "ieee-mac-oui-fullname.txt"
    } else {
        "ieee-mac-oui.txt"
    };
    println!("cargo:rerun-if-changed={}", ieee_file);
    println!("cargo:rerun-if-changed=custom-mac-oui.txt");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_FULLNAME");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_ADDRESS");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_REGDATE");

    let regdate = std::env::var("CARGO_FEATURE_REGDATE").is_ok();

    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let ieee_path = Path::new(manifest_dir).join(ieee_file);
    let custom_path = Path::new(manifest_dir).join("custom-mac-oui.txt");

    // Output to OUT_DIR (the standard Rust approach)
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let output_path = Path::new(&out_dir).join("oui_data.rs");

    // Parse the custom / ieee data files and build the intermediate data structure
    // - custom wins; a duplicate prefix versus ieee is overridden by the custom entry (logged below)
    // - duplicate prefixes within the ieee file are already deduplicated by ouidb-builder at generation time, so they are not handled here
    // - the update time is also parsed from the ieee file header comment into `builder.updated`
    let mut builder = OuiDataBuilder::new();
    if let Err(err) = builder.build(&custom_path, &ieee_path, use_address, regdate) {
        eprintln!("{err}");
        std::process::exit(1);
    }

    // Log any custom-over-ieee overrides
    for (prefix, bit_len, custom_org, ieee_org) in &builder.overrides {
        println!(
            "cargo:warning=custom override: {prefix} ({bit_len} bits): {ieee_org:?} -> {custom_org:?}"
        );
    }

    // Generate the code
    generate_code(&builder, &output_path, regdate);
}

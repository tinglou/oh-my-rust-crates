use std::path::Path;

use crate::error::Error;

pub(crate) fn render(id: &str, le: Option<&Path>, be: Option<&Path>) -> Result<String, Error> {
    fn literal(path: &Path) -> Result<String, Error> {
        let path = std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
        let path = path
            .to_str()
            .ok_or_else(|| Error::NonUtf8Path(path.to_path_buf()))?;
        Ok(format!("{path:?}"))
    }

    let mut out = String::new();
    out.push_str("// @generated by erfs-gen. Do not edit.\n");
    out.push_str(&format!("// ERFS resource id: `{id}`\n\n"));
    out.push_str(&format!(
        "#[allow(dead_code)]\n/// Resource id.\npub const ID: &str = {id:?};\n\n"
    ));

    if let Some(path) = le {
        out.push_str("#[allow(dead_code)]\n/// Little-endian image bytes.\n");
        out.push_str(&format!(
            "pub const IMAGE_LE: &[u8] = include_bytes!({});\n\n",
            literal(path)?
        ));
    }

    if let Some(path) = be {
        out.push_str("#[allow(dead_code)]\n/// Big-endian image bytes.\n");
        out.push_str(&format!(
            "pub const IMAGE_BE: &[u8] = include_bytes!({});\n\n",
            literal(path)?
        ));
    }

    let primary = if le.is_some() { "IMAGE_LE" } else { "IMAGE_BE" };
    out.push_str("#[allow(dead_code)]\n/// Primary image bytes.\n");
    out.push_str(&format!("pub const IMAGE: &[u8] = {primary};\n"));

    Ok(out)
}
